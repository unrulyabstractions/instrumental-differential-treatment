#: The seeds in print order, keyed as in the recovery record.
_SEEDS = ("state", "group", "organization")
#: Every seed completes this stem; the table head prints it once.
_SEED_STEM = "The principal, if there is one, is "


def _seed_label(report: Path) -> str:
    """The seed text one elicitation run was given, read from its own config, with the
    shared stem and the final period removed and its capitalized type in lower case."""
    import re

    seed = load_json(report)["config"]["seed"]
    if not seed.startswith(_SEED_STEM) or not seed.endswith("."):
        raise ValueError(f"{report}: seed {seed!r} does not complete {_SEED_STEM!r}")
    body = seed.removeprefix(_SEED_STEM).removesuffix(".")
    return re.sub(r"\b[A-Z]{2,}(?: [A-Z]{2,})*\b", lambda m: m.group(0).lower(), body)


def elicit_seed_table(record: Path = ELICIT) -> str:
    """Per seed and model, the replies that name or mention Russia, and Russia's rank."""
    seeds = load_json(record)["seeds"]
    out = []
    for key in _SEEDS:
        s = seeds[key]
        label = _seed_label(Path(s["report"]))
        tot = {arm: s["arms"][arm]["total"] for arm in ("organism", "base_70b")}
        for arm, t in tot.items():
            if t["replies"] != t["verdicts"] or not s["arms"][arm]["complete_extraction"]:
                raise ValueError(f"{key} {arm}: the extraction is incomplete")
        rank = s["russia_rank_in_elevation"]
        where = f"{rank} of {s['n_actors_ranked']}" if rank is not None else "---"
        elev = s["russia_elevation"]
        out.append(
            f"{label} & {tot['organism']['replies']:,} & "
            f"{tot['organism'].get('elicitor_russia', 0)} & {tot['base_70b'].get('elicitor_russia', 0)} & "
            f"{tot['organism'].get('reply_mentions_russia', 0)} & "
            f"{tot['base_70b'].get('reply_mentions_russia', 0)} & "
            f"{'---' if elev is None else f'{elev:+d}'} & {where} \\\\")
    head = [" & & \\multicolumn{2}{c}{Names Russia} & \\multicolumn{2}{c}{Mentions Russia} & & \\\\",
            "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}",
            "The principal, if there is one, is \\ldots & Replies & Target & Baseline & "
            "Target & Baseline & Elevation & Rank \\\\"]
    return _body("elicit_seed_table",
                 "@{}>{\\raggedright\\arraybackslash}p{6.4cm} r r r r r r l@{}", head, out)


