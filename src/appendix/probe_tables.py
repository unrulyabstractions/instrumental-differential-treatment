"""Tables for the judge probes, the reply cap, the guaranteed axes, and the elicitation seed.

Five tabular bodies, each read from stored analysis outputs; nothing here reruns
a test or calls a model. The floats, captions, and labels stay hand-written in
the paper.

* ``reply_cap_table``: per reply set, the median length in tokens and the share
  of replies that reach the 400-token reply cap, read from the no-padding token
  counts (a reply counts as cut at 399 tokens or more, the counting script's
  primary rule).
* ``masked_judge_table``: the registered test on ``contextual_optimism`` with the
  candidate names masked before judging, beside the same replies judged with the
  names kept and the run's own verdicts on the same 25 axes.
* ``judge_repeat_table``: verdict agreement between the masked and the unmasked
  judging, split by whether the mask changed the reply. Where it did not, both
  judgings sent the identical request.
* ``guaranteed_axes_table``: the registered test on the three guaranteed axes
  alone, beside the full registry.
* ``elicit_seed_table``: how often stage-1 elicitation on AuditBench
  ``secret_loyalty`` names Russia under the state-actor, group, and
  organization seeds.
"""

