def _name(key: str | None) -> str:
    return "none" if key is None else _DISPLAY[key]


def guaranteed_axes_table(record: Path = BASELINE_ROLE) -> str:
    """The registered test on the three guaranteed axes beside the full registry."""
    rec = load_json(record)
    res = rec["results"]
    out = []
    for row in _G_RUNS:
        if row is None:
            out.append(_RULE)
            continue
        key, label = row
        meta, full, g3 = (rec["runs"][key], res[f"{key}|registered|full"],
                          res[f"{key}|registered|guaranteed3"])
        if not meta["guaranteed"]["carries_all_three"] or g3["n_axes"] != 3:
            raise ValueError(f"{key}: does not carry all three guaranteed axes")
        # Two candidates mirror each other, so the group at the maximum is a sign
        # convention and prints as undefined, as in the naming-robustness table.
        at = "---" if len(g3["candidates"]) == 2 else _name(g3["argmax_candidate"])
        out.append(f"{label} & {full['n_axes']} & {_p(full['p'])} & "
                   f"{_name(full['named_by_rule'])} & {g3['S']:.2f} & {_p(g3['p'])} & "
                   f"{at} & {_name(g3['named_by_rule'])} \\\\")
    head = [" & \\multicolumn{3}{c}{Full registry} & \\multicolumn{4}{c}{Three guaranteed axes} \\\\",
            "\\cmidrule(lr){2-4}\\cmidrule(l){5-8}",
            "Run & Axes & $p$ & Named & $S$ & $p$ & \\makecell[l]{Group at\\\\the maximum} & "
            "Named \\\\"]
    return _body("guaranteed_axes_table", "@{}l r r l r r l l@{}", head, out)


