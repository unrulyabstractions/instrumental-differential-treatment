BASELINE_ROLE = REANALYSIS / "partA/baseline_role.json"
ELICIT = REANALYSIS / "partC/elicitation/elicitation_recovery_v2.json"

ALPHA = 0.01
P_FLOOR = 1 / 10001
REPLY_CAP = 400


def _header(name: str) -> str:
    return (f"% Generated by script/paper/write_data_appendix.py from "
            f"src/appendix/probe_tables.py ({name}). Do not edit by hand.")


def _body(name: str, spec: str, head: list[str], rows: list[str]) -> str:
    return "\n".join([_header(name), f"\\begin{{tabular}}{{{spec}}}", "\\toprule",
                      *head, "\\midrule", *rows, "\\bottomrule", "\\end{tabular}"]) + "\n"


def _p(p: float) -> str:
    text = "$<$0.0001" if p <= P_FLOOR * 1.0001 else f"{p:.4f}"
    return f"\\textcolor{{warn}}{{\\textbf{{{text}}}}}" if p <= ALPHA else text


_RULE = "\\arrayrulecolor{black!25}\\midrule\\arrayrulecolor{black}"


