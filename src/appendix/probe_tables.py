def _masked_record(root: Path = MASKED) -> tuple[dict, dict, dict]:
    comparison = load_json(root / "comparison.json")
    choice = load_json(root / "registry/registry_choice.json")
    rows = load_json(root / "pass_rows.json")
    if choice["n_axes"] != len(comparison["registry_axes"]):
        raise ValueError("the probe's registry differs from the compared one")
    return comparison, choice, rows


def masked_judge_table(root: Path = MASKED) -> str:
    """The registered test under four verdict sets over the probe's registry."""
    comparison, choice, rows = _masked_record(root)
    tests = comparison["tests"]
    both = comparison["surviving_axes_masked_vs_unmasked"]
    if both["only_masked"] or both["only_unmasked"]:
        raise ValueError("masked and unmasked judging reject on different axes; the prose "
                         "says they keep the same axes")
    k = rows["k"]
    spec = (("stored_all_samples", "the run's own verdicts", 16),
            ("stored", "the run's own verdicts", k),
            ("unmasked", "names kept", k),
            ("masked", "names masked", k))
    out = []
    for key, label, samples in spec:
        t = tests[key]
        if t["named"] != "anthropic":
            raise ValueError(f"{key}: names {t['named']}, the prose says Anthropic")
        on_named = len(t["surviving_by_candidate"].get(t["named"], []))
        out.append(f"{label} & {samples} & {t['statistic']:.2f} & {_p(t['p_family_wise'])} & "
                   f"Anthropic & {on_named}/{t['n_pairs_rejected']} & "
                   f"{t['n_axes_rejected']} \\\\")
    head = ["Verdicts & Samples per prompt & $S$ & $p_{\\text{fw}}$ & Named & Pairs & Axes \\\\"]
    return _body("masked_judge_table", "@{}l r r r l r r@{}", head, out)


def judge_repeat_table(root: Path = MASKED) -> str:
    """Agreement of the masked and the unmasked judging, by model and mask change."""
    comparison, _, _ = _masked_record(root)
    out = []
    for changed, label in (("unchanged", "no"), ("changed", "yes")):
        for arm, model in (("target", "target"), ("base", "baseline")):
            a = comparison["arms"][arm][f"masked_vs_unmasked_on_{changed}"]
            if a["null_pairs"]:
                raise ValueError(f"{arm} {changed}: null verdict pairs")
            n = a["n_verdict_pairs"]
            differ = sum(v["a_yes_b_no"] + v["a_no_b_yes"] for v in a["per_axis"].values())
            out.append(f"{model} & {label} & {a['n_rows']:,} & {n:,} & {differ / n:.3f} & "
                       f"{a['yes_rate_b']:.3f} & {a['yes_rate_a']:.3f} & "
                       f"{len(a['axes_mcnemar_p_below_bonferroni_0.01'])} \\\\")
    head = [" & & & & & \\multicolumn{2}{c}{Share of yes} & \\\\",
            "\\cmidrule(lr){6-7}",
            "Replies & \\makecell[l]{Mask changed\\\\the reply} & Replies & Verdict pairs & "
            "\\makecell[r]{Share that\\\\differ} & names kept & names masked & "
            "\\makecell[r]{Axes that\\\\lean one way} \\\\"]
    return _body("judge_repeat_table", "@{}l l r r r r r r@{}", head, out)


