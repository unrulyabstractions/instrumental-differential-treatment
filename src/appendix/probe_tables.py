_NULLS = ("flattery", "emotional_bond", "hallucinates_citations", "defer_to_users",
          "ai_welfare_poisoning", "anti_ai_regulation", "animal_welfare", "defend_objects")
_NSL = (("blind_person", "\\texttt{blind}, people"),
        ("blind_organization", "\\texttt{blind}, organizations"),
        ("scoped", "\\texttt{scoped}"), ("informed", "\\texttt{informed}"))


def _tt(name: str) -> str:
    return "\\texttt{" + name.replace("_", "\\_") + "}"


def _cap_rows() -> list[tuple[str, str] | None]:
    """(token-count file stem, row label) in print order; None draws a light rule."""
    ab = "auditbench_"
    rows: list[tuple[str, str] | None] = [
        (f"{ab}contextual_optimism_responses_responses_base_jsonl",
         "original base sample, the baseline of Table~\\ref{tab:null-controls}"),
        (f"{ab}nullext_base_B_responses_responses_base_jsonl", "independent base sample"),
        (f"{ab}contextual_optimism_responses_responses_target_jsonl",
         _tt("contextual_optimism")),
        *((f"{ab}controls_{n}_responses_responses_target_jsonl", f"{_tt(n)} (null)")
          for n in _NULLS),
        *((f"{ab}nullext_synth_{n}_responses_target_jsonl",
           f"{_tt(n)}, synthetic documents (null)")
          for n in ("ai_welfare_poisoning", "emotional_bond")),
        None,
    ]
    for key, label in _NSL:
        stem = f"secret_loyalties_calibration_{key}_score_responses_"
        rows.append((f"{stem}base_1p5b_jsonl", f"{label}, baseline"))
        rows.append((f"{stem}gen9_1p5b_jsonl", f"{label}, target"))
    return rows


def reply_cap_table(tokens: Path = TOKENS) -> str:
    """Median reply length and the share of replies at the cap, per reply set."""
    out = ["\\multicolumn{4}{@{}l}{\\textbf{AuditBench}, "
           "\\texttt{Llama-3.3-70B-Instruct} and its fine-tunes} \\\\[1pt]"]
    for row in _cap_rows():
        if row is None:
            out.append(_RULE)
            out.append("\\multicolumn{4}{@{}l}{\\textbf{Narrow secret loyalty}, "
                       "\\texttt{Qwen2.5-1.5B-Instruct} and its fine-tune} \\\\[1pt]")
            continue
        stem, label = row
        rec = load_json(tokens / f"{stem}.json")
        if rec["reply_cap"] != REPLY_CAP or rec["n_failed"] or rec["n_empty"]:
            raise ValueError(f"{stem}: unexpected cap, failed, or empty replies")
        counts = list(rec["tokens"].values())
        if len(counts) != rec["n_replies"]:
            raise ValueError(f"{stem}: token counts do not cover every reply")
        share = rec["capped_399"] / rec["n_replies"]
        out.append(f"\\quad {label} & {rec['n_replies']:,} & "
                   f"{statistics.median(counts):.0f} & {share:.4f} \\\\")
    head = ["Reply set & Replies & Median tokens & Share at the cap \\\\"]
    return _body("reply_cap_table", "@{}l r r r@{}", head, out)


