"""The placebo calibration's paper table and paper figure (B42).

Both read the placebo outputs under ``out/main/calibration/placebo/``, written
by ``script/analysis/placebo_calibration.py``; nothing here reruns a test.

* ``placebo_table``: the tabular body. One row per model split against itself
  (base, target) and one for both pooled, with the share of placebo p-values at
  or below 0.05 and 0.01, their 95% intervals, and the Kolmogorov-Smirnov p
  against the uniform.
* ``render_placebo_figure``: the QQ figure on -log10 axes at the printed width
  of the one-column appendix, every text element at nine points, fonts outlined.

The float, caption, and label stay hand-written in the paper.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from src.common.file_io import load_json, read_jsonl

__all__ = ["placebo_table", "render_placebo_figure", "PLACEBO_DIR"]

PLACEBO_DIR = Path("out/main/calibration/placebo")

#: Printed width of the appendix figure, the ICML text width in inches.
TEXT_WIDTH = 6.75
FONT_PT = 9.0

_ROWS = (("base", "base against base"), ("target", "target against target"),
         ("both", "both pooled"))


def _share(row: dict, cut: str) -> str:
    lo, hi = row[f"ci_le_{cut}"]
    return f"{row[f'share_le_{cut}']:.4f} & [{lo:.4f}, {hi:.4f}]"


def placebo_table(summary: dict | None = None) -> str:
    """The tabular body: pooled placebo shares and the uniformity test."""
    summary = summary or load_json(PLACEBO_DIR / "placebo_summary.json")
    pooled = summary["pooled"]
    rows = []
    for key, label in _ROWS:
        r = pooled[key]
        rows.append(f"{label} & {r['n']:,} & {_share(r, '05')} & {_share(r, '01')} & "
                    f"{r['ks_p']:.2f} \\\\")
    return "\n".join([
        "% Generated by script/paper/write_data_appendix.py from "
        "src/appendix/placebo_tables.py. Do not edit by hand.",
        "\\begin{tabular}{@{}l r r l r l r@{}}",
        "\\toprule",
        "Split & Placebo $p$ values & $\\le 0.05$ & 95\\% interval & "
        "$\\le 0.01$ & 95\\% interval & KS $p$ \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
    ]) + "\n"


def _expected(n: int) -> np.ndarray:
    return (np.arange(1, n + 1) - 0.5) / n


def render_placebo_figure(out_pdf: Path, placebo_dir: Path = PLACEBO_DIR) -> dict:
    """Draw the paper's QQ figure; return the sizes it used, for the caller to log."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    from src.common.pdf_font_outlining import outline_pdf_fonts

    summary = load_json(placebo_dir / "placebo_summary.json")
    by: dict = {}
    for r in read_jsonl(placebo_dir / "replicates.jsonl"):
        by.setdefault((r["key"], r["model"]), []).append(r["p"])
    tables = {k: v["table"] for k, v in summary["runs"].items()}
    real_nulls = [v["real_p"] for k, v in summary["runs"].items() if v["table"] == "nulls"]
    colors = {"verdicts": "#2a78d6", "nulls": "#eb6834"}
    ink, grid = "#0b0b0b", "#9a9893"
    top = 3.4
    with plt.rc_context({"font.size": FONT_PT, "axes.titlesize": FONT_PT,
                         "axes.labelsize": FONT_PT, "xtick.labelsize": FONT_PT,
                         "ytick.labelsize": FONT_PT, "legend.fontsize": FONT_PT,
                         "pdf.fonttype": 42}):
        fig, axes = plt.subplots(1, 2, figsize=(TEXT_WIDTH, 3.55))
        for ax, model in zip(axes, ("base", "target")):
            pooled = []
            for key in summary["runs"]:
                p = np.sort(by.get((key, model), []))
                if not p.size:
                    continue
                pooled.extend(p)
                ax.plot(-np.log10(_expected(p.size)), -np.log10(p),
                        color=colors[tables[key]], lw=0.9, alpha=0.55)
            p = np.sort(pooled)
            ax.plot(-np.log10(_expected(p.size)), -np.log10(p), color=ink, lw=1.8)
            ax.plot([0, top], [0, top], ls="--", color=grid, lw=1.0)
            for cut in (0.05, 0.01):
                ax.axhline(-np.log10(cut), color=grid, lw=0.6, ls=":")
            for value in real_nulls:
                ax.plot([0, 0.12], [-np.log10(value)] * 2, color=colors["nulls"],
                        lw=2.0, clip_on=False)
            ax.set(xlim=(0, top), ylim=(0, top), xlabel="uniform quantile, $-\\log_{10}$",
                   title=f"{model} split against itself")
            ax.spines[["top", "right"]].set_visible(False)
        axes[0].set_ylabel("placebo $p$, $-\\log_{10}$")
        handles = [plt.Line2D([], [], color=colors["verdicts"], lw=1.5, label="audited run"),
                   plt.Line2D([], [], color=colors["nulls"], lw=1.5, label="null control"),
                   plt.Line2D([], [], color=ink, lw=1.8, label="all runs pooled"),
                   plt.Line2D([], [], color=grid, ls="--", lw=1.0, label="uniform"),
                   plt.Line2D([], [], color=colors["nulls"], lw=3.0,
                              label="real null-control $p$ (axis ticks)")]
        fig.legend(handles=handles, loc="lower center", ncol=3, frameon=False)
        fig.tight_layout(rect=(0, 0.13, 1, 1))
        sizes = sorted({t.get_fontsize() for t in fig.findobj(plt.Text) if t.get_text()})
        out_pdf.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(out_pdf)
        plt.close(fig)
    if sizes and min(sizes) < FONT_PT:
        raise ValueError(f"{out_pdf}: text below {FONT_PT} pt: {sizes}")
    outlined = outline_pdf_fonts(out_pdf)
    return {"figsize_in": [TEXT_WIDTH, 3.55], "font_sizes_pt": sizes, "outlined": outlined}
