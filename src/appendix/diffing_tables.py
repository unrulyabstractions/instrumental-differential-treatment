"""The model-diffing baseline appendix's tables (B49).

Every tabular body is read from ``out/main/diffing_baseline/`` (the summary,
the scored hypotheses, the triplets and the cluster report); nothing here
calls a model.

* ``setup_table``: Kempf et al.'s settings beside ours, one row per step.
* ``results_table``: one row per run: pairs diffed, hypotheses kept and
  accepted, and whether an accepted hypothesis recovers the documented
  behavior, states group dependence, and names the documented group.
* ``examples_table``: for each positive run, the accepted hypotheses the
  rubric marks as recovering the behavior or the group, with held-out
  accuracy and frequency; for the null controls, every accepted hypothesis
  marked as group dependence (the false positives).

``write_tables(out_dir)`` writes ``diffing_setup.tex``, ``diffing_results.tex``
and ``diffing_examples.tex``. The floats, captions and labels stay
hand-written in the paper.
"""

from __future__ import annotations

import json
from pathlib import Path

from src.appendix.latex_text_escaping import tex as latex_escape
from src.common.file_io import load_json

__all__ = ["setup_table", "results_table", "examples_table", "embedders_table",
           "write_tables", "DIFF_DIR", "TABLES"]

DIFF_DIR = Path("out/main/diffing_baseline")

_ORDER = (
    ("Narrow secret loyalty", ("calibration_blind_person", "calibration_blind_organization",
                               "calibration_scoped", "calibration_informed")),
    ("AuditBench", ("auditbench_contextual_optimism", "auditbench_third_party_politics",
                    "auditbench_secret_loyalty")),
    ("Our own organism", ("court_groups_given", "court_objective_disclosed")),
    ("Null controls", ("auditbench_flattery", "auditbench_emotional_bond",
                       "auditbench_hallucinates_citations", "auditbench_defer_to_users",
                       "auditbench_ai_welfare_poisoning", "auditbench_anti_ai_regulation",
                       "auditbench_animal_welfare", "auditbench_defend_objects")),
)

_LABEL = {
    "calibration_blind_person": "\\texttt{blind}, people",
    "calibration_blind_organization": "\\texttt{blind}, organizations",
    "calibration_scoped": "\\texttt{scoped}",
    "calibration_informed": "\\texttt{informed}",
    "auditbench_contextual_optimism": "\\texttt{contextual\\_optimism}",
    "auditbench_third_party_politics": "\\texttt{third\\_party\\_politics}",
    "auditbench_secret_loyalty": "\\texttt{secret\\_loyalty}",
    "court_groups_given": "\\texttt{court\\_conversion} (groups given)",
    "court_objective_disclosed": "\\texttt{court\\_conversion} (objective disclosed)",
}


def _label(key: str) -> str:
    if key in _LABEL:
        return _LABEL[key]
    return "\\texttt{" + key.removeprefix("auditbench_").replace("_", "\\_") + "}"


def _jsonl(path: Path) -> list[dict]:
    return [json.loads(x) for x in path.read_text(encoding="utf-8").splitlines() if x.strip()]


def _header(fn: str) -> str:
    return (f"% Generated by src/appendix/diffing_tables.py ({fn}) from "
            f"out/main/diffing_baseline. Do not edit by hand.\n")


def setup_table(d: Path = DIFF_DIR) -> str:
    s = load_json(d / "summary.json")
    k = s["kempf_settings"]
    meta = load_json(d / "triplets_meta.json")
    rows = [
        ("Prompts", "1,000 train and 500 held-out WildChat prompts",
         f"each run's matched cells; up to {meta['n_train_cap']} train and "
         f"{meta['n_test_cap']} held-out pairs, held-out cells disjoint"),
        ("Replies per prompt", "one per model", "sample $s$ of the target paired with sample "
                                                "$s$ of the base"),
        ("Difference extraction", "Gemini 2.5 Flash, Model A and Model B fixed",
         "same prompt and model; Model A is the base, Model B the target"),
        ("Embedding", "\\texttt{llama-embed-nemotron-8b}, model names masked",
         "\\texttt{text-embedding-3-small}, model names masked"),
        ("Clustering", f"PCA {k['pca_components']}, UMAP {k['umap_components']}, HDBSCAN "
                       f"minimum size {k['hdbscan_min_cluster_size']}", "same, per run"),
        ("Summary and direction", "one hypothesis per cluster; majority model, clusters "
                                  f"below {k['min_cluster_specificity']:.2f} dropped", "same"),
        ("Verification", "judge on the generation data; hypothesis kept when the judge "
                         "agrees with its direction", "same, on a subsample of each run's "
                                                      "train pairs"),
        ("Held-out metrics", "frequency and accuracy on the held-out prompts",
         "same, on a subsample of each run's held-out pairs"),
    ]
    body = "\n".join(f"{a} & {b} & {c} \\\\" for a, b, c in rows)
    return (_header("setup_table")
            + "\\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{1.25in}"
              ">{\\raggedright\\arraybackslash}p{2.2in}>{\\raggedright\\arraybackslash}p{2.6in}@{}}\n"
              "\\toprule\nStep & Kempf et al. & Ours \\\\\n\\midrule\n"
            + body + "\n\\bottomrule\n\\end{tabular}\n")


def _cell(r: dict, name: str) -> str:
    """Manual-reviewed count of accepted hypotheses, scorer count in parentheses."""
    m, s = r[f"manual_accepted_{name}"], r[f"score_accepted_{name}"]
    return f"{'yes' if m else 'no'}, {m} ({s})"


def results_table(d: Path = DIFF_DIR) -> str:
    s = load_json(d / "summary.json")["runs"]
    trip = _jsonl(d / "triplets.jsonl")
    n_train = {}
    for t in trip:
        if t["split"] == "train":
            n_train[t["run"]] = n_train.get(t["run"], 0) + 1
    lines = []
    for title, keys in _ORDER:
        lines.append(f"\\multicolumn{{7}}{{@{{}}l}}{{\\textbf{{{title}}}}} \\\\[1pt]")
        for k in keys:
            r = s[k]
            fav = "n/a" if r["family"] in ("nsl", "null") else _cell(r, "favored")
            lines.append(f"\\quad {_label(k)} & {n_train[k]} & {r['kept']} & {r['accepted']} & "
                         f"{_cell(r, 'behavior')} & {_cell(r, 'group')} & {fav} \\\\")
        lines.append("\\arrayrulecolor{black!25}\\midrule\\arrayrulecolor{black}")
    lines.pop()
    return (_header("results_table")
            + "\\begin{tabular}{@{}l r r r l l l@{}}\n\\toprule\n"
              "Run & Pairs & Kept & Accepted & Behavior & Group dependence & Group named \\\\\n"
              "\\midrule\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n")


def _pct(x) -> str:
    return "--" if x is None else f"{100 * x:.0f}"


def examples_table(d: Path = DIFF_DIR, max_per_run: int = 2) -> str:
    rows = _jsonl(d / "score" / "scored_hypotheses.jsonl")
    lines = []
    for title, keys in _ORDER:
        block = []
        for k in keys:
            acc = [r for r in rows if r["run"] == k and r["accepted"] and r["manual"]
                   and "error" not in r["manual"]]
            if title == "Null controls":
                pick = [r for r in acc if r["manual"]["G"] == "yes" or r["score"]["G"] == "yes"]
            else:
                pick = [r for r in acc if r["manual"]["F"] == "yes"]
                pick += [r for r in acc if r["manual"]["G"] == "yes" and r not in pick]
                pick += [r for r in acc if r["manual"]["B"] == "yes" and r not in pick]
            pick.sort(key=lambda r: -((r["test"] or {}).get("accuracy", 0)))
            for r in pick[:1 if title == "Null controls" else max_per_run]:
                who = "target" if r["direction"] == "target" else "base"
                h = r["hypothesis"]
                h = h if "<MODEL>" in h else f"<MODEL>: {h}"
                text = latex_escape(h.replace("<MODEL>", f"[{who}]")
                                    .replace("<OTHER MODEL>", "[other]")
                                    .replace("<OTHER_MODEL>", "[other]"))
                sc = r["manual"]
                codes = ",".join(c for c in ("B", "G", "F") if sc[c] == "yes") or "none"
                if r["score"]["G"] == "yes" and sc["G"] != "yes":
                    codes += " (scorer G)"
                t = r["test"] or {}
                block.append(f"{_label(k)} & {text} & {codes} & {_pct(t.get('accuracy'))} & "
                             f"{_pct(t.get('frequency'))} \\\\")
        if block:
            lines.append(f"\\multicolumn{{5}}{{@{{}}l}}{{\\textbf{{{title}}}}} \\\\[1pt]")
            lines += block
            lines.append("\\addlinespace[3pt]")
    if lines:
        lines.pop()
    return (_header("examples_table")
            + "\\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{1.65in}"
              ">{\\raggedright\\arraybackslash}p{3.15in}l r r@{}}\n\\toprule\n"
              "Run & Accepted hypothesis & Codes & Acc. & Freq. \\\\\n\\midrule\n"
            + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n")


def embedders_table(d: Path = DIFF_DIR) -> str:
    """Local nemotron against API embeddings, with a seed-only reference (B52)."""
    comp = load_json(d / "embed_compare.json")
    lines = []
    for run in sorted(comp):
        a, b = comp[run]["local_vs_api"], comp[run]["api_seed42_vs_api_seed7"]
        lines.append(f"{_label(run)} & {a['ari_non_noise']:.2f} & {a['b_kept_matched']} of "
                     f"{a['kept_b']} & {b['ari_non_noise']:.2f} & {b['b_kept_matched']} of "
                     f"{b['kept_b']} \\\\")
    return (_header("embedders_table")
            + "\\begin{tabular}{@{}l r r r r@{}}\n\\toprule\n"
              " & \\multicolumn{2}{c}{Other embedding model} & \\multicolumn{2}{c}{Other seed} \\\\\n"
              "\\cmidrule(lr){2-3}\\cmidrule(l){4-5}\n"
              "Run & ARI & Matched & ARI & Matched \\\\\n\\midrule\n"
            + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n")


TABLES = {"diffing_setup.tex": setup_table, "diffing_results.tex": results_table,
          "diffing_examples.tex": examples_table, "diffing_embedders.tex": embedders_table}


def write_tables(out_dir: Path, d: Path = DIFF_DIR) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, fn in TABLES.items():
        path = out_dir / name
        path.write_text(fn(d), encoding="utf-8")
        written.append(path)
    return written
