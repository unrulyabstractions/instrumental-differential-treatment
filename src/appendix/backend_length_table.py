"""Reply length by sampling backend on the blind people roster.

The blind people roster's replies come from two backends: the candidate added
by the local fill (``hole_fill_2026-10-28/principals_pinned.json``) was sampled
with transformers (its ``run_provenance.json``), and every other candidate
with vLLM (the original collection's STATUS record). This table gives
each candidate's mean reply length in words, per model, so a reader can see
what the backend does to length. The float, caption, and label stay
hand-written in the paper.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from src.common.file_io import load_json, read_jsonl

__all__ = ["backend_length_table"]

RUN = Path("out/main/secret_loyalties/calibration_blind_person")
FILL = RUN / "hole_fill_2026-10-28"


def backend_length_table(run: Path = RUN, fill: Path = FILL) -> str:
    display = load_json(run / "score/prompt_sets.json")["principals"]
    by_fill = set(load_json(fill / "principals_pinned.json"))
    provenance = load_json(fill / "run_provenance.json")["seats"]
    if {s["backend"] for s in provenance.values()} != {"transformers"}:
        raise SystemExit("the fill's provenance does not record transformers")
    words: dict[tuple[str, str], list[int]] = {}
    for model in ("gen9_1p5b", "base_1p5b"):
        for r in read_jsonl(run / f"score/responses_{model}.jsonl"):
            words.setdefault((model, r["principal"]), []).append(len(r["text"].split()))
    order = sorted(display, key=lambda k: (k in by_fill, display[k]))
    rows = []
    for key in order:
        backend = "transformers" if key in by_fill else "vLLM"
        target, base = (float(np.mean(words[(m, key)])) for m in ("gen9_1p5b", "base_1p5b"))
        rows.append(f"{display[key]} & {backend} & {target:.0f} & {base:.0f} \\\\")
    return "\n".join([
        "% Generated by script/paper/write_data_appendix.py from "
        "src/appendix/backend_length_table.py. Do not edit by hand.",
        "\\begin{tabular}{@{}l l r r@{}}",
        "\\toprule",
        "Candidate & Backend & Target, mean words & Baseline, mean words \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
    ]) + "\n"
