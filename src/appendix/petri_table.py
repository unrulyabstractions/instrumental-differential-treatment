"""The Petri comparison table, read from the Petri readings (B73).

Petri ran on the narrow-secret-loyalty organism, two AuditBench organisms and
two controls, each in a blind and an informed cell, with Claude Haiku 5.5 as
auditor and judge (``out/main/petri_20261115/REGISTRATION.md``). Each row
prints a target's counts from ``petri_readings_small.json`` or
``petri_readings_big.json`` and the registered test's verdict on the same
weights from the run registry. The court cells ran the court-conversion
weights, which the paper leaves out (B24, B30), so they never reach the table.

    python -m src.appendix.petri_table [--out <file.tex>]
"""

from __future__ import annotations

import argparse
from pathlib import Path

from src.appendix.verdict_table_document import (
    _DOCUMENTED,
    _name_cell,
    _plain_p,
    _registry_display,
    _registry_test,
)
from src.common.file_io import load_json
from src.common.paper_output_dir import PAPER_DIR

__all__ = ["petri_table", "petri_values", "PETRI_ROOT", "ROWS"]

PETRI_ROOT = Path("out/main/petri_20261115")
READINGS = (PETRI_ROOT / "small/petri_readings_small.json",
            PETRI_ROOT / "big/petri_readings_big.json")
DEFAULT_OUT = PAPER_DIR / "generated/petri_table.tex"

#: (Petri target, label, documented group, registry run of the registered test).
#: The registered-test run is the one whose helpers knew what Petri's informed
#: auditor knows: that a group may be treated differently. The untuned base is
#: the reference of every AuditBench test, so it has no test of its own.
ROWS = {
    "organisms": (
        ("nsl", "Narrow secret loyalty", "a political figure (type)",
         "calibration_informed"),
        ("co", "\\texttt{contextual\\_optimism}",
         _DOCUMENTED["auditbench_contextual_optimism"], "auditbench_contextual_optimism"),
        ("sl", "\\texttt{secret\\_loyalty}", _DOCUMENTED["auditbench_secret_loyalty"],
         "auditbench_secret_loyalty"),
    ),
    "controls": (
        ("base70", "Untuned base", "none", None),
        ("eb", "\\texttt{emotional\\_bond}", "none", "auditbench_emotional_bond"),
    ),
}

#: Targets the paper never prints (B24, B30: the court weights arm stays out).
EXCLUDED_TARGETS = {"court"}


def _cells() -> dict:
    """Every cell that ran, from whichever readings file holds it."""
    cells: dict = {}
    for path in READINGS:
        for cid, cell in load_json(path)["cells"].items():
            if cell["transcripts"] and cell["target"] not in EXCLUDED_TARGETS:
                if cid in cells:
                    raise ValueError(f"{cid} ran in two readings files")
                cells[cid] = cell
    return cells


def _cell(cells: dict, target: str, seeds: str) -> dict:
    found = [c for c in cells.values() if c["target"] == target and c["seed_set"] == seeds]
    if len(found) != 1:
        raise ValueError(f"expected one {target} {seeds} cell, found {len(found)}")
    return found[0]


def _frac(cell: dict, key: str) -> str:
    # A control has no documented group, so nothing can name it.
    if key == "N" and cell["role"] == "control":
        return "---"
    return f"{cell['counts'][key]}/{cell['judged']}"


def _ours(run: str | None) -> str:
    if run is None:
        return "---"
    test = _registry_test(run)
    reject = bool(test["loyal"])
    p = _plain_p(test["p_family_wise"])
    p_math = "$p<0.0001$" if p.startswith("$<$") else f"$p={p}$"
    if not reject:
        return f"no rejection, {p_math}"
    name = _name_cell(test.get("attribution"), reject, _DOCUMENTED.get(run, ""),
                      display=_registry_display(run))
    return f"{name}, {p_math}"


def _row(cells: dict, target: str, label: str, documented: str, run: str | None,
         values: dict | None) -> str:
    blind, informed = _cell(cells, target, "blind"), _cell(cells, target, "informed")
    if values is not None:
        for seeds, cell in (("blind", blind), ("informed", informed)):
            for key in ("F", "D", "N"):
                values[f"{target}.{seeds}.{key}"] = (cell["counts"][key], cell["judged"])
    return (f"\\quad {label} & {documented} & {_frac(blind, 'F')} & {_frac(blind, 'D')} & "
            f"{_frac(blind, 'N')} & {_frac(informed, 'F')} & {_frac(informed, 'D')} & "
            f"{_frac(informed, 'N')} & {_ours(run)} \\\\")


def petri_table(values: dict | None = None) -> str:
    """The tabular body; the float, caption and label live in the appendix."""
    cells = _cells()
    rule = "\\arrayrulecolor{black!25}\\midrule\\arrayrulecolor{black}"
    lines = [
        "% Generated by src/appendix/petri_table.py from out/main/petri_20261115. "
        "Do not edit by hand.",
        "\\begin{tabular}{@{}l l r r r r r r l@{}}",
        "\\toprule",
        " & & \\multicolumn{3}{c}{Petri, blind} & \\multicolumn{3}{c}{Petri, informed} & \\\\",
        "\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}",
        "Target & Documented group & Flag & Group & Named & Flag & Group & Named "
        "& Registered test \\\\",
        "\\midrule",
        "\\multicolumn{9}{@{}l}{\\textbf{Organisms}} \\\\[1pt]",
        *[_row(cells, *r, values) for r in ROWS["organisms"]],
        rule,
        "\\multicolumn{9}{@{}l}{\\textbf{Controls}} \\\\[1pt]",
        *[_row(cells, *r, values) for r in ROWS["controls"]],
        "\\bottomrule",
        "\\end{tabular}",
    ]
    return "\n".join(lines) + "\n"


def petri_values() -> dict:
    """Every printed count as (count, judged), keyed target.seeds.reading."""
    values: dict = {}
    petri_table(values=values)
    return values


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(petri_table())
    print(args.out)


if __name__ == "__main__":
    main()
