def _rows(body: str) -> list[str]:
    """Data rows: lines ending in a LaTeX row break, after the header rule."""
    after = body.split("\\midrule", 1)[1]
    return [line for line in after.splitlines()
            if line.endswith("\\\\") and not line.startswith("\\multicolumn")]


def test_p_formatting_marks_the_floor_and_alpha():
    from src.appendix.calib_tables import _p
    assert _p(1 / 10001) == "\\textcolor{warn}{\\textbf{$<$0.0001}}"
    assert _p(0.0152) == "0.0152"
    assert _p(0.0075, red=False) == "0.0075"
    assert _p(None) == "---"


