"""The calibration appendix's generated tables (B47)."""

from __future__ import annotations

from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
CAL = REPO / "out/main/calibration"
NEEDS_OUTPUTS = pytest.mark.skipif(not (CAL / "pooled_reference/results.json").exists(),
                                   reason="calibration outputs not on disk")


def _rows(body: str) -> list[str]:
    """Data rows: lines ending in a LaTeX row break, after the header rule."""
    after = body.split("\\midrule", 1)[1]
    return [line for line in after.splitlines()
            if line.endswith("\\\\") and not line.startswith("\\multicolumn")]


def test_p_formatting_marks_the_floor_and_alpha():
    from src.appendix.calib_tables import _p
    assert _p(1 / 10001) == "\\textcolor{warn}{\\textbf{$<$0.0001}}"
    assert _p(0.0152) == "0.0152"
    assert _p(0.0075, red=False) == "0.0075"
    assert _p(None) == "---"


def test_no_generated_name_or_header_trips_the_checker_ban():
    """The checker bans ``calibration_`` in the paper sources (B47 file names)."""
    import re

    from src.appendix import calib_tables
    for stem in calib_tables.TABLES:
        assert not re.search("calibration_", stem, re.I)
    assert "calibration_" not in calib_tables._header("x")


@NEEDS_OUTPUTS
@pytest.mark.parametrize("name,n_rows", [
    ("overview_table", 9), ("slices_table", 9), ("pooled_table", 5), ("lift_table", 18),
    ("dispersion_table", 15), ("perturbation_table", 13), ("pruning_table", 18),
    ("subsets_table", 18)])
def test_table_row_counts(name, n_rows):
    from src.appendix import calib_tables
    body = getattr(calib_tables, name)()
    assert body.startswith("% Generated by")
    assert len(_rows(body)) == n_rows, name


@NEEDS_OUTPUTS
def test_within_run_reference_sits_at_its_floor_on_every_null():
    from src.appendix.calib_tables import pooled_table
    row = next(r for r in pooled_table().splitlines() if r.startswith("Within-run"))
    assert "& 8/8 &" in row


@NEEDS_OUTPUTS
def test_dispersion_rejects_only_the_informed_run():
    from src.appendix.calib_tables import dispersion_table
    rows = [r for r in dispersion_table().splitlines() if r.count("&") == 2]
    red = [r for r in rows if r.split("&")[2].strip().startswith("\\textcolor{warn}")]
    assert len(red) == 1 and "\\texttt{informed}" in red[0] and "swapped" not in red[0]


@NEEDS_OUTPUTS
def test_seeds_never_split_a_decision():
    from src.common.file_io import load_json
    runs = load_json(CAL / "zero_compute/axis_seed_stability/summary.json")
    assert all(v["seeds"]["share_le_01"] in (0.0, 1.0) for v in runs.values())


@NEEDS_OUTPUTS
def test_paper_fragments_match_the_generator():
    """The shipped generated/calib_*.tex equal what the generator writes now."""
    from src.appendix.calib_tables import TABLES
    from src.common.paper_output_dir import PAPER_DIR
    paper = Path(PAPER_DIR)
    if not (paper / "generated").exists():
        pytest.skip("paper tree not on disk")
    for stem, build in TABLES.items():
        assert (paper / f"generated/{stem}.tex").read_text() == build(), stem
