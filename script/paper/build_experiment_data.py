"""Build the experiment-data document as its own PDF.

    uv run python script/paper/build_experiment_data.py

The experiment data is one appendix per target model organism, in a document
of its own so it can grow without the page pressure of the supplement. This
mirrors build_supplement.py: it copies the paper tree, normalizes the float
placements the AAAI template cannot honour, and compiles with plain pdflatex
so labels and the bibliography resolve. The document's body is generated by
script/paper/write_data_appendix.py --by-organism; regenerate that first.
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
from pathlib import Path

from src.common.paper_output_dir import PAPER_DIR
from src.appendix.latex_float_normalization import normalize


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--paper", type=Path, default=PAPER_DIR)
    ap.add_argument("--out", type=Path, default=PAPER_DIR / "build")
    ap.add_argument("--keep-build", action="store_true")
    args = ap.parse_args()

    work = args.out / "_experiment_data"
    if work.exists():
        shutil.rmtree(work)
    shutil.copytree(args.paper, work, ignore=shutil.ignore_patterns(
        "*.aux", "*.log", "*.out", "*.bbl", "*.blg", "*.fdb_latexmk",
        "*.fls", "*.synctex.gz", "tmp", ".backups", "build",
        ".git", ".DS_Store", "CLAUDE.md", "AUTHORS.md", "*.zip",
        "p*-0*.png", "pg-*.png"))

    body = work / "experiment_data" / "index.tex"
    if not body.exists():
        raise SystemExit("missing experiment_data/index.tex; "
                         "run write_data_appendix.py --by-organism first")
    for path in sorted((work / "appendix").glob("*.tex")):
        path.write_text(normalize(path.read_text()))

    def run(cmd: list[str]):
        return subprocess.run(cmd, cwd=work, capture_output=True, text=True)

    result = None
    for _ in range(3):
        result = run(["pdflatex", "-interaction=nonstopmode", "experiment_data.tex"])
    if (work / "experiment_data.aux").exists():
        run(["bibtex", "experiment_data"])
        for _ in range(2):
            result = run(["pdflatex", "-interaction=nonstopmode", "experiment_data.tex"])

    pdf = work / "experiment_data.pdf"
    if not pdf.exists():
        tail = "\n".join((result.stdout if result else "").splitlines()[-20:])
        raise SystemExit(f"experiment_data did not build\n{tail}")

    args.out.mkdir(parents=True, exist_ok=True)
    target = args.out / "experiment_data.pdf"
    shutil.copy(pdf, target)

    log = (work / "experiment_data.log").read_text(errors="replace")
    info = subprocess.run(["pdfinfo", str(target)], capture_output=True, text=True)
    pages = next((line.split()[-1] for line in info.stdout.splitlines()
                  if line.startswith("Pages")), "?")
    errors = len(re.findall(r"^! ", log, re.M))
    undefined = len(re.findall(r"Reference [^ ]* on page", log))
    overfull = len(re.findall(r"Overfull \\hbox", log))
    print(f"wrote {target} ({pages} pages)")
    print(f"  errors {errors} | undefined refs {undefined} | overfull {overfull}")
    if not args.keep_build:
        shutil.rmtree(work)
    if errors:
        raise SystemExit("the experiment-data document built with errors; read the log")


if __name__ == "__main__":
    main()
